//  DailyPrompts.swift
//  NoFap
//
//  Вопросы для новой записи в дневнике — идут по кругу, а не совсем
//  случайно, чтобы один и тот же вопрос не выпадал повторно раньше,
//  чем закончится полный круг.
//

import Foundation

enum DailyPrompts {

    static let all: [String] = [
        "Какая ситуация сегодня почти заставила тебя потянуться за легким дофамином?",
        "Что ты сделал сегодня такого, за что будешь уважать себя завтра?",
        "Куда ты сегодня инвестировал энергию, которую сберег благодаря воздержанию?",
        "Твой главный триггер за последние 24 часа — и как ты его обошел?"
    ]

    private static let key = "dailyPromptIndex"

    /// Следующий вопрос по кругу. Используется и при автоматическом
    /// открытии экрана, и при ручном нажатии «Сменить вопрос» — так
    /// поведение предсказуемо и не повторяется без причины.
    static func next(defaults: UserDefaults = .standard) -> String {
        let last = defaults.integer(forKey: key)
        let next = (last + 1) % all.count
        defaults.set(next, forKey: key)
        return all[next]
    }
}
