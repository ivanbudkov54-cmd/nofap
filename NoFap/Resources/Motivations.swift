import Foundation

enum Motivations {

    static let all: [String] = [
        "Тяга — это волна. Она поднимается, но всегда спадает.",
        "Не обязательно чувствовать себя сильным. Достаточно не открывать браузер.",
        "Каждый отказ делает следующий чуть легче.",
        "Ты не борешься с собой. Ты возвращаешь себе внимание.",
        "Скука и усталость врут громче всего. Переспи с этим решением.",
        "Срыв не отменяет пройденный путь. Он просто часть пути.",
        "Сделай что-то физическое прямо сейчас: вода, воздух, десять приседаний.",
        "Мозгу нужно время. Ты уже даёшь ему это время.",
        "Один день — это мало для результата и много для привычки.",
        "Тебе не нужно объяснять никому, зачем ты это делаешь.",
        "Самое сложное — первые двадцать минут. Дальше проще.",
        "Ты сейчас не отказываешь себе. Ты выбираешь что-то получше.",
        "Одиночество — это триггер, а не причина. Напиши кому-нибудь.",
        "То, что тяжело сегодня, станет фоном через месяц.",
        "Ошибка — не повод обнулять всё. Просто отметь и иди дальше."
    ]

    /// Одна и та же фраза в течение всего дня.
    static func today(for date: Date = Date()) -> String {
        let day = Calendar.current.ordinality(of: .day, in: .era, for: date) ?? 0
        return all[day % all.count]
    }
}
