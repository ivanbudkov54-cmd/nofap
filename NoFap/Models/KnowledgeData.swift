// MARK: - My Journey

/// День программы — тексты друга из DailyFactsStore, как есть.
struct JourneyDay: Identifiable, Hashable {
    let day: Int
    let phase: String
    let title: String
    let badge: String
    let biochemistry: String
    let realFeel: String
    let trapWarning: String
    let tacticalAction: String
    var id: Int { day }

    nonisolated init(fact: DailyFact) {
        day = fact.dayNumber
        phase = fact.phaseTitle
        title = fact.headline
        badge = fact.markerBadge
        biochemistry = fact.biochemistry
        realFeel = fact.realFeel
        trapWarning = fact.trapWarning
        tacticalAction = fact.tacticalAction
    }
}

enum JourneyLibrary {
    static let totalDays = 45
    static let all: [JourneyDay] = DailyFactsStore.dailyFacts.map(JourneyDay.init)
}

// MARK: - Urge Simulator

struct UrgeChoice: Identifiable, Hashable {
    let id: String
    let text: String
    /// Ведёт к следующему шагу того же сценария — nil, если этот выбор
    /// уже финальный и должен показать исход.
    let nextStepId: String?
    /// Текст исхода — заполнен только у финальных выборов.
    let outcome: String?
    let isFailure: Bool

    init(id: String, text: String, nextStepId: String? = nil, outcome: String? = nil, isFailure: Bool = false) {
        self.id = id
        self.text = text
        self.nextStepId = nextStepId
        self.outcome = outcome
        self.isFailure = isFailure
    }
}

struct UrgeStep: Identifiable, Hashable {
    let id: String
    let text: String
    let choices: [UrgeChoice]
}

struct UrgeScenario: Identifiable, Hashable {
    let id: String
    let title: String
    let subtitle: String
    let icon: String
    let startStepId: String
    let steps: [UrgeStep]

    /// Шаги хранятся массивом (для Hashable/предсказуемого порядка),
    /// но нужны по id — словарь строится один раз при обращении.
    var stepsById: [String: UrgeStep] {
        Dictionary(uniqueKeysWithValues: steps.map { ($0.id, $0) })
    }
}

